#include <LPC17xx.h>

void delay(void) {
    unsigned int i;
    for(int i = 0; i < 10000; ++i);
}
 
int main(void) {
    SystemInit();
    SystemCoreClockUpdate();

    LPC_PINCON->PINSEL0 = 0;
    LPC_GPIO0->FIODIR |= (1 << 4);

    while(1) {
        LPC_GPIO0->FIOSET = (1 << 4);
        delay();
        LPC_GPIO0->FIOCLR = (1 << 4);
        delay();
    }
}
